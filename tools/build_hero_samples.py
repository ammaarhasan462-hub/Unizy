#!/usr/bin/env python3
"""Writes web/components/story/heroSamples.js: the typical first-year answers from site/data/samples.json for the homepage
try box's subjects (SUBJECTS in tryhero.js). The box opens with one filled in so visitors can press Mark straight away.
Run after changing samples.json or the homepage subjects:  python3 tools/build_hero_samples.py"""
import json, pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'web/components/story/tryhero.js').read_text()
codes = sorted(set(re.findall(r"code: '([A-Z0-9]+)'", src.split('const SUBJECTS')[0] + src.split('const SUBJECTS')[1].split('];')[0])))
samples = json.loads((root / 'site/data/samples.json').read_text())
out = {c: samples[c] for c in codes if c in samples}
js = ('// Generated by tools/build_hero_samples.py from site/data/samples.json. Do not edit by hand.\n'
      '// code -> { q: first 8 characters of the starter question id, a: a typical first-year answer }\n'
      'export const HERO_SAMPLES = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
(root / 'web/components/story/heroSamples.js').write_text(js)
print('wrote', len(out), 'samples:', ', '.join(out))
